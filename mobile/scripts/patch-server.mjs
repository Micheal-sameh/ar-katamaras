// One-off patch of mobile/: Ar-katamaras name + package id, readings from katamaras.avarewase.com (Katameros as fallback).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const edit = (file, pairs) => {
  const p = path.join(mobile, file);
  let s = fs.readFileSync(p, 'utf8');
  for (const [from, to] of pairs) {
    if (!s.includes(from)) throw new Error(`${file}: anchor not found: ${from.slice(0, 60)}`);
    s = s.split(from).join(to);
  }
  fs.writeFileSync(p, s);
};

const APP_ID = 'com.avarewase.ar_katamaras'; // Android ids cannot contain a hyphen

edit('capacitor.config.json', [['"appId": "com.avarewase.readings"', `"appId": "${APP_ID}"`], ['"appName": "Avarewase Readings"', '"appName": "Ar-katamaras"']]);
edit('android/app/build.gradle', [['applicationId "com.avarewase.readings"', `applicationId "${APP_ID}"`]]);
edit('android/app/src/main/res/values/strings.xml', [
  ['<string name="app_name">Avarewase Readings</string>', '<string name="app_name">Ar-katamaras</string>'],
  ['<string name="title_activity_main">Avarewase Readings</string>', '<string name="title_activity_main">Ar-katamaras</string>'],
  ['<string name="package_name">com.avarewase.readings</string>', `<string name="package_name">${APP_ID}</string>`],
  ['<string name="custom_url_scheme">com.avarewase.readings</string>', `<string name="custom_url_scheme">${APP_ID}</string>`],
]);
edit('package.json', [['"name": "avarewase-readings-mobile"', '"name": "ar-katamaras"'], ['"description": "Android app for the Avarewase daily readings"', '"description": "Ar-katamaras: Android app for the daily readings"']]);
