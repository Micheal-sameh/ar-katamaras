// Copies the web app (../public) into ./www and writes a config.js that answers the app's
// /api/readings calls on the phone itself, by asking the Katameros API directly (the same
// katameros.js the desktop app uses). Days already seen are kept in localStorage for offline use.
const fs = require('fs');
const path = require('path');

const from = path.resolve(__dirname, '../../public');
const to = path.resolve(__dirname, '../www');
const skip = new Set(['sw.js', 'index.php', 'robots.txt', 'favicon.ico', '.htaccess', 'storage', 'hot']);

fs.rmSync(to, { recursive: true, force: true });
fs.cpSync(from, to, { recursive: true, filter: (src) => !skip.has(path.basename(src)) });

const katameros = fs.readFileSync(path.resolve(__dirname, '../../desktop/src/katameros.js'), 'utf8');

fs.writeFileSync(path.join(to, 'js/config.js'),
`/* Android build: generated by mobile/scripts/sync.js. */
(function () {
  var PREFIX = 'katameros-day:';
  var store = {
    get: function (k) { try { return localStorage.getItem(PREFIX + k); } catch (e) { return null; } },
    set: function (k, v) {
      try { localStorage.setItem(PREFIX + k, v); } catch (e) {
        // storage full: drop the oldest kept days and try once more
        try {
          Object.keys(localStorage).filter(function (x) { return x.indexOf(PREFIX) === 0; }).sort().slice(0, 20)
            .forEach(function (x) { localStorage.removeItem(x); });
          localStorage.setItem(PREFIX + k, v);
        } catch (e2) { /* keep working without the offline copy */ }
      }
    },
  };
  var modules = {
    fs: {
      mkdirSync: function () {},
      readFileSync: function (f) { var v = store.get(f); if (v === null) throw new Error('missing'); return v; },
      writeFileSync: function (f, v) { store.set(f, v); },
    },
    path: { join: function () { return Array.prototype.join.call(arguments, '/'); } },
  };
  var process = { env: {} };
  var module = { exports: {} };
  var require = function (name) { return modules[name] || {}; /* ../app/js/coptic.js is already loaded as a script */ };
  ${katameros.replace(/\n/g, '\n  ')}
  var direct = new module.exports.KatamerosDirect('days');
  var realFetch = window.fetch.bind(window);
  window.fetch = function (input, init) {
    var raw = typeof input === 'string' ? input : input.url;
    if (raw.indexOf('/api/readings/') !== 0) return realFetch(input, init);
    var url = new URL(raw, 'http://local');
    var iso = decodeURIComponent(url.pathname.split('/').filter(Boolean).pop() || '');
    var headers = { 'Content-Type': 'application/json' };
    return direct.get(iso, url.searchParams.get('lang') || 'ar', Number(url.searchParams.get('bible')) || 0).then(
      function (day) { return new Response(JSON.stringify({ data: day }), { headers: headers }); },
      function (e) {
        var status = e instanceof module.exports.ReadingsError ? e.status : 503;
        var message = status === 503 ? 'The readings could not be loaded. Check your internet connection and try again.' : e.message;
        return new Response(JSON.stringify({ message: message }), { status: status, headers: headers });
      });
  };
  window.APP_CONFIG = { API_BASE: '/api/readings', ALLOW_DEMO: false };
})();
`);
// On-the-fly updates (see scripts/updater.js and README).
const pkg = require('../package.json');
const baseUrl = String(require('../update.config.json').baseUrl || '').replace(/\/+$/, '');
fs.writeFileSync(path.join(to, 'js/updater.js'),
  fs.readFileSync(path.join(__dirname, 'updater.js'), 'utf8').replace('__BASE_URL__', baseUrl).replace('__BUILT_IN__', pkg.version));
const indexFile = path.join(to, 'index.html');
fs.writeFileSync(indexFile, fs.readFileSync(indexFile, 'utf8').replace('<script src="js/app.js"></script>', '<script src="js/updater.js"></script>\n  <script src="js/app.js"></script>'));
console.log('Synced web app into mobile/www (web version ' + pkg.version + ')');
